/// A single node to be created on the canvas by the Build command.
#[derive(Serialize, Deserialize)]
pub struct BuildNode {
    pub id: String,
    pub node_type: String,
    pub title: String,
    pub description: String,
}

/// A directed connection between two nodes in the Build plan.
#[derive(Serialize, Deserialize)]
pub struct BuildEdge {
    pub source: String,
    pub target: String,
    pub label: String,
}

/// The full Build plan returned to the frontend.
#[derive(Serialize, Deserialize)]
pub struct BuildPlan {
    pub nodes: Vec<BuildNode>,
    pub edges: Vec<BuildEdge>,
    pub summary: String,
}

/// Build Mode: interpret a natural-language prompt and generate a structured
/// plan of canvas nodes + connections to create, taking into account the
/// existing canvas state so the plan integrates smoothly.
#[tauri::command]
pub async fn build_from_prompt(prompt: String, map_context: String) -> Result<BuildPlan, String> {
    let full_prompt = format!(
        "{ASTROLABE_SYSTEM_KNOWLEDGE}\n\n\
         You are Astrolabe in Build Mode. The user wants you to BUILD elements directly on their canvas. \
         Current canvas state: {map_context}. \
         User request: \"{prompt}\". \
         Analyse the request and the canvas, then return ONLY a valid JSON object with exactly these keys: \
         1. \"nodes\": array of objects, each with: \
            \"id\" (short string like \"n1\", \"n2\" — must be unique), \
            \"node_type\" (one of: index_card, note, milestone), \
            \"title\" (max 6 words), \
            \"description\" (1-2 sentences, empty string for notes/milestones). \
         2. \"edges\": array of objects, each with: \
            \"source\" (node id from this plan or existing canvas node id), \
            \"target\" (node id from this plan or existing canvas node id), \
            \"label\" (short relationship label or empty string). \
         3. \"summary\": one sentence describing what was built. \
         Rules: create 3-8 nodes max; avoid duplicating titles already on the canvas; \
         use realistic, specific titles relevant to the request."
    );

    let response_text = tokio::task::spawn_blocking(move || {
        let client = ollama_client();
        let resp = client
            .post(format!("{OLLAMA_BASE}/api/generate"))
            .json(&GenerateRequest {
                model: FAST_MODEL,
                prompt: &full_prompt,
                stream: false,
                format: "json",
            })
            .send()
            .map_err(|e| format!("Ollama request failed: {e}"))?;
        parse_ollama_response(resp)
    })
    .await
    .map_err(|e| format!("Task join error: {e}"))??;

    let plan: BuildPlan = serde_json::from_str(&response_text)
        .map_err(|e| format!("Failed to parse build plan: {e}\nRaw: {response_text}"))?;

    Ok(plan)
}
/// Oracle: answer a question about the user's vision board / life map.
/// Uses the deep model for nuanced strategic guidance.
