#[derive(Serialize)]
struct GenerateRequest<'a> {
    model: &'a str,
    prompt: &'a str,
    stream: bool,
    format: &'a str, // pass "json" to enforce structured output
}

/// For free-text generation (no JSON format enforcement)
#[derive(Serialize)]
struct GenerateFreeRequest<'a> {
    model: &'a str,
    prompt: &'a str,
    stream: bool,
}



// â”€â”€â”€ Helpers â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

fn ollama_client() -> reqwest::blocking::Client {
    reqwest::blocking::Client::builder()
        .timeout(std::time::Duration::from_secs(120))
        .build()
        .expect("failed to build HTTP client")
}

/// Read an Ollama `/api/generate` response robustly.
/// Handles error payloads (`{"error": "..."}`) and missing/unexpected fields
/// gracefully, returning a descriptive message instead of a raw serde error.
fn parse_ollama_response(resp: reqwest::blocking::Response) -> Result<String, String> {
    let status = resp.status();
    let text = resp
        .text()
        .map_err(|e| format!("Ollama read failed: {e}"))?;

    let val: serde_json::Value = serde_json::from_str(&text)
        .map_err(|e| format!("Ollama returned non-JSON (status {status}): {e}\nBody: {text}"))?;

    if let Some(err) = val.get("error").and_then(|v| v.as_str()) {
        return Err(format!("Ollama error: {err}"));
    }

    val.get("response")
        .and_then(|v| v.as_str())
        .map(|s| s.to_string())
        .ok_or_else(|| {
            format!("Ollama response missing 'response' field (status {status}).\nBody: {text}")
        })
}

