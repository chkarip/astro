const FAST_MODEL: &str = "gemma4:e4b";
const DEEP_MODEL: &str = "qwen2.5:7b-instruct";

// ─── System Knowledge ─────────────────────────────────────────────────────────

/// Injected into every Oracle/Build prompt so the model knows exactly what
/// Astrolabe is, what every node type means, and how to interpret the canvas.
const ASTROLABE_SYSTEM_KNOWLEDGE: &str = "\
## What is Astrolabe?
Astrolabe is a visual life-mapping and project-orchestration desktop app built with Tauri + React. \
The user works on an infinite canvas where they connect nodes (cards, notes, milestones, etc.) \
to plan projects, track goals, capture ideas, and execute tasks — all powered by local AI.

## Node Types (Schema Knowledge)
- **golden** — The central anchor of the canvas. Represents the user's primary vision, north-star goal, \
  or the single most important objective. Clicking it opens the Oracle chat panel. There is usually only one.
- **index_card** — A standard task or project card. Has a title, description, and a status \
  (pending → in_progress → done). This is the workhorse node for actionable work items.
- **note** — A free-text sticky note for raw thoughts, reminders, or reference material. No status.
- **idea_sphere** — A bubble for brainstormed ideas that haven't been committed to action yet. \
  Free-text, no status. Used during ideation.
- **milestone** — A labelled checkpoint or delivery marker on a timeline. Marks a significant achievement \
  or phase boundary. Has a label but no status tracking.
- **terminal** — A live terminal node. The user can drag an index_card onto it to auto-execute \
  its task as PowerShell commands generated by the AI. Shows a log of command output in real time.
- **cluster_group** — A visual grouping container created by the Smart Cluster feature. \
  Wraps semantically related nodes under a shared category label.

## Node Statuses (index_card only)
- **pending** — Not started yet.
- **in_progress** — Actively being worked on.
- **done** — Completed.

## Edge / Connection meaning
Edges represent intentional relationships between nodes — e.g. a dependency, a workflow step, \
a sub-task relationship, or a conceptual link. The label on an edge describes the relationship.

## Key Features (Feature Knowledge)
- **Oracle (Chat Mode)** — AI chat panel anchored to the golden node. The user asks questions about \
  their canvas, gets strategic advice, explores ideas, or requests analysis. Uses the deep model.
- **Build Mode** — Switches the Oracle panel to construction mode. The user describes what they want \
  to create in plain English and the AI materialises nodes + edges directly on the canvas.
- **Orbit Menu** — Right-clicking or long-pressing a node opens a radial menu with actions: \
  Sprout (generate sub-ideas), Cluster (group related nodes), Run (execute via terminal), etc.
- **Sprout** — AI generates 4 creative sub-idea cards that logically extend a selected node, \
  aware of everything already on the canvas to avoid duplication.
- **Smart Cluster** — AI groups loose idea_sphere nodes into semantic categories and wraps them \
  in cluster_group containers.
- **Terminal Execution** — Drop an index_card onto a terminal node; the AI generates and runs \
  the PowerShell commands needed to complete that task automatically.
- **Profiles** — Fully isolated workspaces. Each profile has its own canvas, nodes, edges, and \
  AI context. Switching profiles is like switching between completely separate projects.
- **Command Palette** — Keyboard shortcut overlay for power-user actions (create nodes, switch modes, etc.).

## How to read the map context
The map context is a JSON object: { nodes: [...], connections: [...] }. \
Each node has: id, type (one of the node types above), title, status. \
Each connection has: from (source node id), to (target node id). \
Use this to understand what the user is working on and give grounded, specific answers.\
";


