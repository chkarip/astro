/// Rich idea node returned by the Sprout command.
#[derive(Serialize, Deserialize)]
pub struct NodeIdea {
    pub title: String,
    pub description: String,
}

/// Sprout: generate 4 rich sub-ideas (title + description) that extend a specific node,
/// taking into account the full canvas context to avoid repeating existing nodes.
#[tauri::command]
pub async fn generate_node_ideas(
    target_title: String,
    target_desc: String,
    global_context: String,
) -> Result<Vec<NodeIdea>, String> {
    let prompt = format!(
        "{ASTROLABE_SYSTEM_KNOWLEDGE}\n\n\
         You are Astrolabe running the Sprout feature. \
         The entire current canvas for context: {global_context}. \
         The user wants to expand on this specific node: '{target_title}' — '{target_desc}'. \
         Generate exactly 4 logical, creative, or strategic sub-ideas that follow from this node, \
         using the canvas context to avoid repeating existing nodes. \
         Return ONLY a valid JSON array of objects. Each object must have a 'title' (max 5 words) and a \
         'description' (1 to 2 short sentences explaining the strategy)."
    );

    let response_text = tokio::task::spawn_blocking(move || {
        let client = ollama_client();
        let resp = client
            .post(format!("{OLLAMA_BASE}/api/generate"))
            .json(&GenerateRequest {
                model: FAST_MODEL,
                prompt: &prompt,
                stream: false,
                format: "json",
            })
            .send()
            .map_err(|e| format!("Ollama request failed: {e}"))?;
        parse_ollama_response(resp)
    })
    .await
    .map_err(|e| format!("Task join error: {e}"))??;

    let ideas: Vec<NodeIdea> = serde_json::from_str(&response_text)
        .map_err(|e| format!("Failed to parse node ideas JSON: {e}\nGot: {response_text}"))?;

    Ok(ideas)
}

/// Smart Clustering: group loose idea nodes into 2–4 semantic categories.
/// Returns the raw JSON string from Ollama (array of { cluster_name, node_ids }).
#[tauri::command]
pub async fn cluster_ideas(nodes_json: String) -> Result<String, String> {
    let prompt = format!(
        "You are a visionary architect. Group the following list of brainstormed ideas into 2 to 4 high-level semantic categories. \
         Here are the ideas: {nodes_json}. \
         Return ONLY a valid JSON array of objects. Each object must have: \
         1. 'cluster_name' (a short, descriptive category title) \
         2. 'node_ids' (an array of the exact string IDs belonging to this cluster)."
    );

    tokio::task::spawn_blocking(move || {
        let client = ollama_client();
        let resp = client
            .post(format!("{OLLAMA_BASE}/api/generate"))
            .json(&GenerateRequest {
                model: FAST_MODEL,
                prompt: &prompt,
                stream: false,
                format: "json",
            })
            .send()
            .map_err(|e| format!("Ollama request failed: {e}"))?;
        parse_ollama_response(resp)
    })
    .await
    .map_err(|e| format!("Task join error: {e}"))?
}
